// The user's side of the M14 journey, shared by the local runner (`pnpm test:m14`) and the live
// suite (`test:mvp:cloud` suite m14): a clean consumer with the PACKED CLI and scaffolder
// installed from tarballs, protected profiles, scaffolded and locked projects, the CLI as a
// separate process with a clean environment, an MCP client for `mcp setup` files and a reverse
// proxy for the prefix case. Nothing here imports the workspace's own CLI.
import { execFileSync, spawn } from "node:child_process";
import { chmod, cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createServer, request as httpRequest } from "node:http";
import { request as httpsRequest } from "node:https";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const { URL, setTimeout, clearTimeout } = globalThis;

function exec(program, args, options = {}) {
  return execFileSync(program, args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    maxBuffer: 64 * 1024 * 1024,
    ...options,
  }).trim();
}

/**
 * Installs the packed framework packages the CLI needs (from the recipe's staged tarballs, in
 * dependency order as a registry exposes them) and the packed scaffolder into `dir`.
 */
export async function installPackedConsumer({ dir, framework, frameworkDir, root, packDir }) {
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, "package.json"), '{"name":"m14-consumer","private":true}\n');
  const packed = JSON.parse(
    exec("pnpm", ["pack", "--json", "--pack-destination", packDir], {
      cwd: join(root, "packages/create-embody-app"),
    }),
  );
  const tarballs = new Map(framework.map((entry) => [entry.name, join(frameworkDir, entry.file)]));
  for (const name of [
    "@embody/core",
    "@embody/cloud-contracts",
    "@embody/storage",
    "@embody/auth",
    "@embody/mcp",
    "@embody/host",
    "@embody/cli",
  ])
    exec("npm", ["install", "--no-audit", "--no-fund", "--save-exact", tarballs.get(name)], {
      cwd: dir,
    });
  exec(
    "npm",
    ["install", "--no-audit", "--no-fund", (Array.isArray(packed) ? packed[0] : packed).filename],
    { cwd: dir },
  );
  return {
    cliBin: join(dir, "node_modules/@embody/cli/bin/embody.js"),
    createBin: join(dir, "node_modules/create-embody-app/dist/bin.js"),
  };
}

/** The user's protected profile file (mode 0600, as the CLI requires for stored tokens). */
export async function writeProfiles(home, profiles) {
  const configFile = join(home, ".config/embody/config.json");
  await mkdir(join(home, ".config/embody"), { recursive: true });
  await writeFile(configFile, JSON.stringify({ defaultProfile: "deployer", profiles }), {
    mode: 0o600,
  });
  await chmod(configFile, 0o600);
  return configFile;
}

/**
 * The user's two projects, generated by the packed scaffolder and locked against the framework
 * registry with the recipe's pnpm, each with a local `.env` secret that must never leave it.
 */
export async function createProjects({ dir, createBin, registryUrl, names, canary }) {
  await mkdir(dir, { recursive: true });
  // Async on purpose: the framework registry may answer from this same process.
  const lock = (cwd) =>
    new Promise((resolve, reject) => {
      const child = spawn(
        "corepack",
        [
          "pnpm@11.25.0",
          "install",
          "--lockfile-only",
          "--ignore-scripts",
          `--config.@embody:registry=${registryUrl}`,
          "--config.registry=https://registry.npmjs.org/",
        ],
        { cwd, stdio: ["ignore", "ignore", "inherit"], env: { ...process.env, CI: "true" } },
      );
      child.on("error", reject);
      child.on("close", (code) =>
        code === 0 ? resolve() : reject(new Error(`lockfile generation failed in ${cwd}`)),
      );
    });
  const scaffold = async (name, flag) => {
    exec(process.execPath, [createBin, name, flag, "--no-install"], { cwd: dir });
    const project = join(dir, name);
    await writeFile(join(project, ".env"), `DATABASE_URL=postgresql://user:${canary}@db/app\n`);
    await lock(project);
    return project;
  };
  const cards = await scaffold(names.cards, "--request-only");
  const flow = await scaffold(names.flow, "--durable");
  let variants = 0;
  /** A copy of `base` changed for one journey case. */
  const variant = async (base, kind) => {
    variants += 1;
    const target = join(dir, `${kind}-${variants}`);
    await cp(base, target, { recursive: true });
    if (kind === "v2" || kind === "v3")
      await writeFile(join(target, "src/release.ts"), `export const release = "${kind}";\n`);
    if (kind === "malformed") await rm(join(target, "embody.config.ts"));
    if (kind === "broken") {
      const pkg = JSON.parse(await readFile(join(target, "package.json"), "utf8"));
      pkg.scripts.build = "node -e process.exit(3)";
      await writeFile(join(target, "package.json"), `${JSON.stringify(pkg, null, 2)}\n`);
    }
    return target;
  };
  return { cards, flow, variant };
}

/** The packed CLI as a separate process per call, with a clean environment. */
export function cliRunner({ cliBin, cwd, home, configFile, cache, env = {} }) {
  return (args, options = {}) =>
    new Promise((resolve) => {
      const child = spawn(
        process.execPath,
        [cliBin, ...(options.profile ? ["--profile", options.profile] : []), ...args],
        {
          cwd,
          env: {
            PATH: process.env.PATH,
            HOME: home,
            EMBODY_CONFIG: configFile,
            EMBODY_CACHE_DIR: cache,
            ...env,
            ...options.env,
          },
          stdio: ["pipe", "pipe", "pipe"],
        },
      );
      let out = "";
      let err = "";
      let interrupted = false;
      child.stdout.on("data", (chunk) => (out += chunk));
      child.stderr.on("data", (chunk) => {
        err += chunk;
        if (!interrupted && options.interruptWhen?.(err)) {
          interrupted = true;
          child.kill("SIGINT");
        }
      });
      child.stdin.end(options.stdin ?? "");
      const guard = setTimeout(() => child.kill("SIGKILL"), 45 * 60_000);
      child.on("close", (code, signal) => {
        clearTimeout(guard);
        resolve({ code: code ?? (signal === "SIGINT" ? 130 : 1), out, err });
      });
    });
}

/** An official MCP SDK client built from an `embody mcp setup --write` file. */
export function mcpClientFactory(require) {
  return async (file) => {
    const { Client } = await import(
      pathToFileURL(require.resolve("@modelcontextprotocol/sdk/client/index.js")).href
    );
    const { StreamableHTTPClientTransport } = await import(
      pathToFileURL(require.resolve("@modelcontextprotocol/sdk/client/streamableHttp.js")).href
    );
    const config = JSON.parse(await readFile(file, "utf8")).mcpServers.embody;
    const transport = new StreamableHTTPClientTransport(new URL(config.url), {
      requestInit: { headers: config.headers },
    });
    const client = new Client({ name: "m14-journey", version: "1.0.0" });
    await client.connect(transport);
    return {
      tools: async () => (await client.listTools()).tools.map((tool) => tool.name),
      call: (name, args) => client.callTool({ name, arguments: args }),
      close: () => client.close(),
    };
  };
}

/**
 * A loopback reverse proxy serving `upstream` under `/edge` (the M14.c reverse-proxy prefix),
 * streaming both ways. Returns its base URL (`…/edge`).
 */
export async function startEdgeProxy(upstream) {
  const target = new URL(upstream);
  const send = target.protocol === "https:" ? httpsRequest : httpRequest;
  const server = createServer((request, response) => {
    if (!request.url?.startsWith("/edge/")) return void response.writeHead(404).end();
    const proxied = send(
      {
        host: target.hostname,
        port: target.port || (target.protocol === "https:" ? 443 : 80),
        method: request.method,
        path: `${target.pathname.replace(/\/+$/, "")}${request.url.slice("/edge".length)}`,
        headers: { ...request.headers, host: target.host },
      },
      (reply) => {
        response.writeHead(reply.statusCode ?? 502, reply.headers);
        reply.pipe(response);
      },
    );
    proxied.on("error", () => response.destroy());
    request.pipe(proxied);
  });
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  return {
    url: `http://127.0.0.1:${server.address().port}/edge`,
    close: () => new Promise((resolve) => server.close(() => resolve())),
  };
}
